#!/usr/bin/python3
"""Local host compatibility for Lake Comparator, with isolation preserved.

This host permits fresh network namespaces but denies the NETLINK_ROUTE
socket bubblewrap uses to bring loopback up. Create the empty namespace
first, then let bubblewrap retain only that private namespace. Every phase
is offline, including the dependency phase normally allowed network access.
All original mount, environment, process and namespace restrictions remain.
This is local verification infrastructure, not a change to Palomar's runner.
"""

import errno
import os
import sys


# Exactly the options generated by this pinned Lake's buildSandboxArgs.
# Parse arities: an option value may itself be the string "--".
ARITY = {
    "--ro-bind": 2, "--tmpfs": 1, "--dir": 1, "--dev": 1,
    "--proc": 1, "--clearenv": 0, "--bind": 2, "--setenv": 2,
    "--unshare-all": 0, "--die-with-parent": 0, "--new-session": 0,
    "--share-net": 0, "--chdir": 1,
}

args = sys.argv[1:]
index = 0
seen = set()
while index < len(args) and args[index] != "--":
    option = args[index]
    if option not in ARITY:
        raise SystemExit("Unsupported Comparator sandbox option: " + option)
    seen.add(option)
    index += 1 + ARITY[option]
if index >= len(args) - 1:
    raise SystemExit("Missing Comparator sandbox command separator or command")
required = {"--unshare-all", "--die-with-parent", "--new-session", "--clearenv"}
if not required <= seen:
    raise SystemExit("Missing required Comparator sandbox protections")

# No supported argument refers to an inherited extra descriptor. Preserve
# only standard input/output/error; prevent socket or namespace FD leakage.
for descriptor in os.listdir("/proc/self/fd"):
    fd = int(descriptor)
    if fd > 2:
        try:
            os.close(fd)
        except OSError as error:
            if error.errno != errno.EBADF:
                raise

# Keep the invoking UID instead of mapping it to root. Explicitly clear all
# capabilities as an additional invariant. Append after --unshare-all and
# before the command separator; no original option is removed or rewritten.
os.execv("/usr/bin/unshare", [
    "unshare", "--user", "--map-current-user", "--net", "--",
    "/usr/bin/bwrap", *args[:index],
    "--share-net", "--cap-drop", "ALL", "--", *args[index + 1:],
])
